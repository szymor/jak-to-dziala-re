size_t cp1250_to_utf8(const char *src, size_t n, char *dst, size_t dstlen)
{
    size_t o = 0;
    for (size_t i = 0; i < n && src[i]; i++) {
        uint16_t u = to_unicode[(uint8_t)src[i]];
        char buf[3];
        size_t k;
        if (u < 0x80) {
            buf[0] = (char)u;
            k = 1;
        } else if (u < 0x800) {
            buf[0] = (char)(0xC0 | (u >> 6));
            buf[1] = (char)(0x80 | (u & 0x3F));
            k = 2;
        } else {
            buf[0] = (char)(0xE0 | (u >> 12));
            buf[1] = (char)(0x80 | ((u >> 6) & 0x3F));
            buf[2] = (char)(0x80 | (u & 0x3F));
            k = 3;
        }
        if (o + k >= dstlen)
            break;
        memcpy(dst + o, buf, k);
        o += k;
    }
    if (dstlen)
        dst[o] = 0;
    return o;
}

size_t utf8_to_cp1250(const char *src, char *dst, size_t dstlen)
{
    size_t o = 0;
    const unsigned char *s = (const unsigned char *)src;
    while (*s && o + 1 < dstlen) {
        uint32_t u;
        int k;
        if (*s < 0x80) u = *s, k = 1;
        else if ((*s & 0xE0) == 0xC0 && s[1]) u = ((uint32_t)(*s & 0x1F) << 6) | (s[1] & 0x3F), k = 2;
        else if ((*s & 0xF0) == 0xE0 && s[1] && s[2]) u = ((uint32_t)(*s & 0x0F) << 12) | ((uint32_t)(s[1] & 0x3F) << 6) | (s[2] & 0x3F), k = 3;
        else { s++; continue; }
        s += k;
        for (int b = 0; b < 256; b++)
            if (to_unicode[b] == u && u != 0xFFFD) {
                dst[o++] = (char)b;
                break;
            }
    }
    if (dstlen)
        dst[o] = 0;
    return o;
}

int cp1250_compare(const char *a, size_t na, const char *b, size_t nb)
{
    size_t n = na < nb ? na : nb;
    for (size_t i = 0; i < n; i++) {
        uint32_t ka = sort_key[(uint8_t)a[i]], kb = sort_key[(uint8_t)b[i]];
        if (ka != kb)
            return ka < kb ? -1 : 1;
    }
    return na < nb ? -1 : na > nb ? 1 : 0;
}
